@Serializable
data class CompanyUser(
    val userId: Uuid? = null,
    val createDate: Instant? = null,
    val updateDate: Instant? = null,
    val status: String? = null,
    val username: String? = null,
    val email: String? = null,
    val firstName: String? = null,
    val lastName: String? = null,
    val fullName: String? = null,
    val languagePreference: String? = null,
    val timezone: String? = null,
    val lastLoginDate: Instant? = null,
    // Strings preserve the backend's enum wire representation (name or display value).
    val accountVerificationStatus: String? = null,
    val twoFactorAuthentication: Boolean? = null,
    val companyId: Uuid? = null,
    val companyName: String? = null,
    val authApiToken: Uuid? = null,
    // Spring Data @Transient excludes these from Cassandra, not from JSON.
    val roles: List<CompanyUserRole>? = null,
)

@Serializable
data class CompanyUserRole(
    val createDate: Instant? = null,
    val updateDate: Instant? = null,
    val status: String? = null,
    val roleId: Uuid? = null,
    val roleName: String? = null,
    val userId: Uuid? = null,
    val roleNameEnum: String? = null,
)